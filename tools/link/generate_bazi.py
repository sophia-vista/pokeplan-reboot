#!/usr/bin/env python3
from datetime import datetime
from pathlib import Path
from lunar_python import Lunar, Solar

FIRST, LAST = 1901, 2099
JIE = [("小寒", "XIAO_HAN"), ("立春", "LI_CHUN"), ("惊蛰", "JING_ZHE"), ("清明", "清明"), ("立夏", "立夏"), ("芒种", "芒种"),
       ("小暑", "小暑"), ("立秋", "立秋"), ("白露", "白露"), ("寒露", "寒露"), ("立冬", "立冬"), ("大雪", "DA_XUE")]
EPOCH = datetime(1900, 1, 1)

def minutes(s):
    return round((datetime(s.getYear(), s.getMonth(), s.getDay(), s.getHour(), s.getMinute(), int(s.getSecond())) - EPOCH).total_seconds() / 60)

jie_rows, new_years = [], []
for y in range(FIRST, LAST + 1):
    table = []
    for ref in (y - 1, y, y + 1):
        table += list(Solar.fromYmd(ref, 6, 1).getLunar().getJieQiTable().items())
    row = []
    for names in JIE:
        hit = {v.toYmdHms(): v for k, v in table if k in names and v.getYear() == y}.values()
        hit = list(hit)
        assert len(hit) == 1, (y, names, len(hit))
        row.append(minutes(hit[0]))
    jie_rows.append(row)
    ny = Lunar.fromYmd(y, 1, 1).getSolar()
    new_years.append(ny.getMonth() * 100 + ny.getDay())

out = ["// Generated by tools/link/generate_bazi.py: do not edit by hand.", "package app.pokeplan.link", "",
       "/** Solar-term and Chinese New Year tables for [BaZi]. 1901 to 2099. */", "internal object BaZiTables {",
       f"    const val FIRST_YEAR = {FIRST}", f"    const val LAST_YEAR = {LAST}",
       "    /** Per year, the twelve jie (Xiaohan, Lichun, Jingzhe, Qingming, Lixia, Mangzhong, Xiaoshu, Liqiu, Bailu, Hanlu, Lidong, Daxue) as minutes since 1900-01-01 00:00 Beijing time. */",
       '    val JIE_MINUTES: String = ""']
lines = [" ".join(map(str, r)) for r in jie_rows]
out[-1] = '    val JIE_MINUTES: String = "' + "\\n\" +\n        \"".join(lines) + '"'
out += ["", "    /** Per year, Chinese New Year as month*100+day (Gregorian). */",
        '    val NEW_YEAR: String = "' + " ".join(map(str, new_years)) + '"', "}", ""]
Path(__file__).resolve().parents[2].joinpath("link-core/src/commonMain/kotlin/app/pokeplan/link/BaZiTables.kt").write_text("\n".join(out), encoding="utf-8")
print("wrote", len(jie_rows), "years")
