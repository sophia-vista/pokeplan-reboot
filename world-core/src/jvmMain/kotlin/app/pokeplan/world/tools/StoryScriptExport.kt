package app.pokeplan.world.tools

import app.pokeplan.core.dex.Dex
import app.pokeplan.world.Story
import app.pokeplan.world.WorldLayer
import app.pokeplan.world.story.SceneEvent
import app.pokeplan.world.story.StoryCatalog
import app.pokeplan.world.story.StoryScene
import java.io.File

fun main(args: Array<String>) {
    val out = StringBuilder()
    out.appendLine("# PokéLife: story and script (generated)").appendLine()
    out.appendLine("Generated by `./gradlew :world-core:storyScript` from `world-core/.../story/*Chapters.kt`. Do not edit this file: rewrite the Kotlin (or send the rewritten text back) and regenerate. `{buddy}` is the player's chosen buddy, `{player}` the player's name; a line's `(expression)` is the face shown. First-pass writing.").appendLine()
    out.appendLine("## The opening").appendLine().appendLine("Mew's Unofficial Welcome: plays first on a new save; belongs to no region.").appendLine()
    for (scene in StoryCatalog.intro().scenes) scene(out, scene)
    out.appendLine("## Follow-up Mythical introductions").appendLine().appendLine("Optional, self-contained, and belonging to no region: the story archive offers them; finishing one invites its Mythical to join.").appendLine()
    for (ep in StoryCatalog.mythicalEpisodes()) {
        out.appendLine("### ${ep.title}").appendLine()
        out.appendLine("*Episode key:* `${ep.key}` · *summary:* ${ep.summary}").appendLine()
        for (scene in ep.scenes) scene(out, scene)
    }
    for (layer in WorldLayer.entries) {
        out.appendLine("## ${layer.label}").appendLine().appendLine(layer.blurb).appendLine()
        for (c in Story.chaptersOf(layer)) {
            out.appendLine("### Chapter ${c.number}: ${c.title}").appendLine()
            out.appendLine("*Summary:* ${c.summary}").appendLine()
            val ep = StoryCatalog.episodeFor(layer, c.number)
            if (ep == null) { out.appendLine("(no scenes yet: the chapter plays its title card)").appendLine(); continue }
            for (scene in ep.scenes) scene(out, scene)
        }
    }
    val target = File(args.firstOrNull() ?: "docs/world-story-script.md")
    target.writeText(out.toString())
    println("wrote ${target.path}: ${StoryCatalog.all().sumOf { it.scenes.size }} scenes")
}

private fun scene(out: StringBuilder, s: StoryScene) {
    val cast = s.cast.joinToString(", ") { c -> c.displayName.replace("big_", "") + (c.speciesId?.let { " (${Dex.species(it).name})" } ?: "") }
    out.appendLine("#### Scene: ${s.title}  \n`${s.id}` · ${s.type.name.lowercase()} · ${s.dungeonId?.let { "dungeon $it" } ?: "background ${s.background}"} · cast: $cast").appendLine()
    fun name(who: String?): String = if (who == null) "" else s.cast.firstOrNull { it.id == who }?.displayName?.replace("big_", "") ?: who
    fun gap() { if (!out.endsWith("\n\n")) out.appendLine() }
    fun events(list: List<SceneEvent>, indent: String) {
        for (e in list) when (e) {
            is SceneEvent.Say -> {
                gap()
                val face = e.expression?.let { " (${it.name.lowercase()})" } ?: ""
                if (e.who == null) out.appendLine("$indent*${e.text}*").appendLine() else out.appendLine("$indent**${name(e.who)}**$face: ${e.text}").appendLine()
            }
            is SceneEvent.Show -> out.appendLine("$indent- ${name(e.who)} appears").also { }
            is SceneEvent.Hide -> out.appendLine("$indent- ${name(e.who)} leaves")
            is SceneEvent.Move -> out.appendLine("$indent- ${name(e.who)} walks")
            is SceneEvent.Cry -> out.appendLine("$indent- ${name(e.who)} cries out")
            is SceneEvent.Shake -> out.appendLine("$indent- the screen shakes")
            is SceneEvent.Flash -> out.appendLine("$indent- a flash")
            is SceneEvent.Fade -> out.appendLine("$indent- fade ${if (e.toBlack) "to black" else "in"}")
            is SceneEvent.Emote -> out.appendLine("$indent- ${name(e.who)}: ${e.mark}")
            is SceneEvent.Item -> out.appendLine("$indent- an item lies on the floor (${e.itemId})")
            is SceneEvent.Sound -> out.appendLine("$indent- sound: ${e.name}")
            is SceneEvent.Choice -> {
                gap()
                e.prompt?.let { out.appendLine("$indent*$it*").appendLine() }
                out.appendLine("${indent}**Choice:** " + e.options.joinToString("  /  ") { "“${it.label}” → `${it.flag}`" }).appendLine()
            }
            is SceneEvent.Branch -> { gap(); out.appendLine("${indent}**If `${e.flag}`:**").appendLine(); events(e.events, "$indent> ") }
            else -> {}
        }
    }
    events(s.events, "")
}
