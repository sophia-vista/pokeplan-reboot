            exit("koffing", 2.4f); exit("zubat", 1.8f)
            walk(BUDDY, 7.0f to 2.8f)
            say(BUDDY, "Got it!", HAPPY)
            narr("{buddy} picks up the item, then looks at you.")
            say(BUDDY, "You helped me back there. Thanks.", NORMAL)
