package app.pokeplan.shared.tools

import app.pokeplan.shared.dex.Dex
import app.pokeplan.shared.dex.HatchRules
import app.pokeplan.shared.dex.Region
import app.pokeplan.shared.dex.SpeciesInfo
import app.pokeplan.shared.model.Rarity
import java.io.File

/**
 * Writes the candidates report used to curate the Home Region (docs/home-region-candidates.md).
 * Run with `./gradlew :shared:curationReport`.
 */
fun main(args: Array<String>) {
    val out = File(args.firstOrNull() ?: "docs/home-region-candidates.md")
    out.parentFile?.mkdirs()
    out.writeText(report())
    println("wrote ${out.path}")
}

private fun children(id: Int): List<SpeciesInfo> =
    Dex.species.filter { it.evolvesFrom == id }

private fun render(s: SpeciesInfo): String {
    val next = children(s.id)
    return when (next.size) {
        0 -> s.name
        1 -> s.name + " → " + render(next[0])
        else -> s.name + " → (" + next.joinToString(" / ") { render(it) } + ")"
    }
}

private fun lineMembers(root: Int): List<SpeciesInfo> = Dex.species.filter { Dex.lineRoot(it.id) == root }

private fun typeLabel(members: List<SpeciesInfo>): String {
    val finals = members.filter { m -> children(m.id).isEmpty() }
    return finals.flatMap { Dex.defaultForm(it.id).types }.distinct().joinToString("/") { it.label }
}

private fun report(): String {
    val home = Dex.regionDex(Region.HOME).map { it.id }.toSet()
    val roots = Dex.species.filter { it.evolvesFrom == null && !it.isSpecial }
    val byTier = roots.groupBy { HatchRules.rarity(it.id)!! }
    val sb = StringBuilder()
    sb.appendLine("# Home Region candidates")
    sb.appendLine()
    sb.appendLine("Generated by `./gradlew :shared:curationReport`. Do not edit by hand.")
    sb.appendLine()
    sb.appendLine("Every Pokémon line that can hatch from an egg, with its rarity tier. **Tier belongs to the whole evolution line** (set by the strongest form in it), so every species in a line shares it. `Home` marks lines that have at least one species in the current Home Region.")
    sb.appendLine()
    sb.appendLine("| Tier | Lines | In Home now |")
    sb.appendLine("|---|---|---|")
    for (r in Rarity.entries) {
        val lines = byTier[r].orEmpty()
        sb.appendLine("| ${r.label} | ${lines.size} | ${lines.count { l -> lineMembers(l.id).any { it.id in home } }} |")
    }
    sb.appendLine()
    for (r in Rarity.entries) {
        val lines = byTier[r].orEmpty().sortedBy { it.id }
        sb.appendLine("## ${r.label} (${lines.size} lines)")
        sb.appendLine()
        sb.appendLine("| Line | Types (final forms) | Gen | Species | Home |")
        sb.appendLine("|---|---|---|---|---|")
        for (root in lines) {
            val members = lineMembers(root.id)
            sb.appendLine("| ${render(root)} | ${typeLabel(members)} | ${root.generation} | ${members.size} | ${if (members.any { it.id in home }) "yes" else ""} |")
        }
        sb.appendLine()
    }
    sb.appendLine("## Quest and milestone only (never hatch from eggs)")
    sb.appendLine()
    sb.appendLine("These can be in the Home dex, but are earned through quests (legendary-class) or milestones (mythical), not eggs.")
    sb.appendLine()
    val special = Dex.species.filter { it.isSpecial }
    fun kind(s: SpeciesInfo) = when {
        s.isMythical -> "mythical"
        s.isLegendary -> "legendary"
        s.identifier in app.pokeplan.shared.dex.SpecialSpecies.ultraBeasts -> "ultra beast"
        else -> "paradox"
    }
    for (k in listOf("legendary", "mythical", "ultra beast", "paradox")) {
        sb.appendLine("- **$k:** " + special.filter { kind(it) == k }.joinToString(", ") { it.name })
    }
    sb.appendLine()
    return sb.toString()
}
