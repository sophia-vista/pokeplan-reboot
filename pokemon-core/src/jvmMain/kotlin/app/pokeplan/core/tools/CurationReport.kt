package app.pokeplan.core.tools

import app.pokeplan.core.dex.Dex
import app.pokeplan.core.dex.HatchRules
import app.pokeplan.core.dex.Region
import app.pokeplan.core.dex.SpeciesInfo
import app.pokeplan.core.model.Rarity
import java.io.File

/**
 * Writes the candidates report used to curate a module region (docs/region-candidates.md).
 * Run with `./gradlew :pokemon-core:curationReport`.
 */
fun main(args: Array<String>) {
    val out = File(args.firstOrNull() ?: "docs/region-candidates.md")
    out.parentFile?.mkdirs()
    out.writeText(report())
    println("wrote ${out.path}")
}

private fun children(id: Int): List<SpeciesInfo> =
    Dex.species.filter { it.evolvesFrom == id }

private fun render(s: SpeciesInfo): String {
    val next = children(s.id)
    return when (next.size) {
        0 -> s.name
        1 -> s.name + " → " + render(next[0])
        else -> s.name + " → (" + next.joinToString(" / ") { render(it) } + ")"
    }
}

private fun lineMembers(root: Int): List<SpeciesInfo> = Dex.species.filter { Dex.lineRoot(it.id) == root }

private fun typeLabel(members: List<SpeciesInfo>): String {
    val finals = members.filter { m -> children(m.id).isEmpty() }
    return finals.flatMap { Dex.defaultForm(it.id).types }.distinct().joinToString("/") { it.label }
}

private fun report(): String {
    val modules = Region.entries.filter { it.isModule }
    val regionOf: Map<Int, Region> = modules.flatMap { r -> Dex.regionDex(r).map { it.id to r } }.toMap()
    fun regionsOf(members: List<SpeciesInfo>) = members.mapNotNull { regionOf[it.id] }.distinct()
    fun short(r: Region) = r.label.removeSuffix(" Region")
    val roots = Dex.species.filter { it.evolvesFrom == null && !it.isSpecial }
    val byTier = roots.groupBy { HatchRules.rarity(it.id)!! }
    val sb = StringBuilder()
    sb.appendLine("# Module region candidates")
    sb.appendLine()
    sb.appendLine("Generated by `./gradlew :pokemon-core:curationReport`. Do not edit by hand.")
    sb.appendLine()
    sb.appendLine("Every Pokémon line that can hatch from an egg, with its rarity tier. **Tier belongs to the whole evolution line** (set by the strongest form in it), so every species in a line shares it. `Region` names the module region (${modules.joinToString(", ") { it.label }}) that already has at least one species of the line; a species is in at most one module region.")
    sb.appendLine()
    sb.appendLine("| Tier | Lines | " + modules.joinToString(" | ") { "In ${short(it)} now" } + " | Free |")
    sb.appendLine("|---|---|" + modules.joinToString("") { "---|" } + "---|")
    for (r in Rarity.entries) {
        val lines = byTier[r].orEmpty().map { regionsOf(lineMembers(it.id)) }
        sb.appendLine("| ${r.label} | ${lines.size} | " + modules.joinToString(" | ") { m -> "${lines.count { m in it }}" } + " | ${lines.count { it.isEmpty() }} |")
    }
    sb.appendLine()
    for (r in Rarity.entries) {
        val lines = byTier[r].orEmpty().sortedBy { it.id }
        sb.appendLine("## ${r.label} (${lines.size} lines)")
        sb.appendLine()
        sb.appendLine("| Line | Types (final forms) | Gen | Species | Region |")
        sb.appendLine("|---|---|---|---|---|")
        for (root in lines) {
            val members = lineMembers(root.id)
            sb.appendLine("| ${render(root)} | ${typeLabel(members)} | ${root.generation} | ${members.size} | ${regionsOf(members).joinToString(", ") { short(it) }} |")
        }
        sb.appendLine()
    }
    sb.appendLine("## Quest and milestone only (never hatch from eggs)")
    sb.appendLine()
    sb.appendLine("These can be in a module region's dex, but are earned through quests (legendary-class) or milestones (mythical), not eggs. Those already in a module region are marked with it.")
    sb.appendLine()
    val special = Dex.species.filter { it.isSpecial }
    fun kind(s: SpeciesInfo) = when {
        s.isMythical -> "mythical"
        s.isLegendary -> "legendary"
        s.identifier in app.pokeplan.core.dex.SpecialSpecies.ultraBeasts -> "ultra beast"
        else -> "paradox"
    }
    for (k in listOf("legendary", "mythical", "ultra beast", "paradox")) {
        sb.appendLine("- **$k:** " + special.filter { kind(it) == k }.joinToString(", ") { s -> s.name + (regionOf[s.id]?.let { " (${short(it)})" } ?: "") })
    }
    sb.appendLine()
    return sb.toString()
}
